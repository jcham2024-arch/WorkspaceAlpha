#!/usr/bin/env python3
"""Generate AgentCards from the agent registry (A2A-style discovery).

Reads .agent/agents.json (generated by registry.py) plus
.agent/models.json and emits .agent/agent-cards.json — one card per
agent with name, description, version, capabilities/skills per
agent, auth/extensions, url, documentationUrl.

  python3 .agent/tools/agent_cards.py
Cards are regenerated any time the registry changes; profiles stay
the source of truth, the registry is the index, cards are exports.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
REGISTRY = ROOT / ".agent" / "agents.json"
MODELS = ROOT / ".agent" / "models.json"
OUT = ROOT / ".agent" / "agent-cards.json"

def card(agent, version):
    tier = agent.get("model_tier", "")
    tier_key = next((k for k in ("high-thinking", "low-thinking", "no-thinking") if k in tier), "")
    return {
        "name": agent.get("agent", "unnamed"),
        "description": agent.get("role", "")[:200],
        "version": version,
        "url": f"file://.agent/{agent.get('profile_file', '')}",
        "documentationUrl": ".agent/agent.md",
        "capabilities": {
            "skills": agent.get("skills", []),
            "tools": agent.get("tools", []),
            "mcp_allowlist": agent.get("mcp_allowlist", []),
            "stage": agent.get("stage", ""),
        },
        "extensions": {"model_tier": tier, "model": agent.get("model_suggestion", "unspecified")},
    }

def main():
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    version = reg.get("factory_version", "0.1.0")
    cards = [card(a, version) for a in reg.get("agents", [])]
    OUT.write_text(json.dumps({"version": 1, "factory_version": version, "cards": cards}, indent=2, ensure_ascii=False) + "\n",
                   encoding="utf-8")
    print(f"wrote {OUT} ({len(cards)} cards)")

if __name__ == "__main__":
    main()
